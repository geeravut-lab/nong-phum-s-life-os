export const dict: Record<Lang, Dict> = { th, en };

/** The dictionary for a language. */
export function dictFor(lang: Lang): Dict {
  return dict[lang];
}

/**
 * Current UI language outside React: route head() functions and server code
 * cannot call useI18n(). Reads the same localStorage key the provider writes;
 * on the server (SSR of / and /auth) there is no window, so Thai — the app's
 * default — is used, and the client re-runs head() on its next navigation.
 */
export function currentLang(): Lang {
  if (typeof window === "undefined") return "th";
  try {
    return window.localStorage.getItem("phum-lang") === "en" ? "en" : "th";
  } catch {
    return "th";
  }
}

/** Language name for AI prompts ("Reply in …"). Not a UI string; one place instead of five. */
export function langName(lang: Lang): "English" | "Thai" {
  return lang === "en" ? "English" : "Thai";
}

/** Pick the current language's text from a { th, en } pair, as stored in benefits data. */
export function localized(lang: Lang, pair: { th: string; en: string }): string {
  return lang === "en" ? pair.en : pair.th;
}

type MetaKey = { [K in keyof Dict]: K extends `meta_${string}_title` ? K : never }[keyof Dict];

/**
 * <head> tags for a route. `page` is the middle part of a meta_<page>_title key.
 *
 * Only <title> follows the user's language. description and og:* stay Thai on
 * purpose: they exist for crawlers and link previews, which only ever see the
 * server-rendered HTML — where there is no localStorage and Thai is the
 * default. Making them follow the client language would leave the SSR Thai
 * tag and a client English tag side by side after hydration (React keeps both
 * when a hoisted <meta> differs), while <title> is a singleton the browser
 * simply updates. The English descriptions in the dictionary are correct and
 * kept for the day the app serves language-specific SEO.
 */
export function routeMeta(page: MetaKey extends `meta_${infer P}_title` ? P : never) {
  const title = dictFor(currentLang())[`meta_${page}_title` as MetaKey] as string;
  const thTitle = dict.th[`meta_${page}_title` as MetaKey] as string;
  const description = dict.th[`meta_${page}_desc` as keyof Dict] as string;
  return [
    { title },
    { name: "description", content: description },
    { property: "og:title", content: thTitle },
    { property: "og:description", content: description },
    { property: "og:type", content: "website" },
    { name: "twitter:card", content: "summary_large_image" },
  ];
}
